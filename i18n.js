  function lookup(s) {
    if (has(s)) return ZH[s];
    const cap = s.charAt(0).toUpperCase() + s.slice(1);
    return cap !== s && has(cap) ? ZH[cap] : null;
  }
  // Returns the translation of a trimmed string, or null when there is none.
